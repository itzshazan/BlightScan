// Regenerates migrations/0004_seed.sql from web/lib/diseases.ts so the database copy of the
// disease library never drifts from the site. Run with Node 22.6+ (type stripping):
//   node supabase/scripts/generate-seed.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const { diseases } = await import(pathToFileURL(path.join(here, "../../web/lib/diseases.ts")).href);

const str = (v) => (v == null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => (a?.length ? `array[${a.map(str).join(", ")}]` : "null");
const json = (v) => (v == null ? "null" : `${str(JSON.stringify(v))}::jsonb`);

const rows = diseases.map(
  (d) => `  (${[
    str(d.slug),
    str(d.label),
    str(d.name),
    str(d.pathogen),
    str(d.pathogenType),
    str(d.severity),
    str(d.deck),
    str(d.summary),
    str(d.shortSymptom),
    arr(d.symptoms),
    json(d.conditions),
    str(d.favourable_conditions),
    str(d.spread_mode),
    arr(d.treatment_organic),
    arr(d.treatment_chemical),
    arr(d.prevention),
    str(d.related),
  ].join(",\n   ")})`
);

const sql = `-- Seed data. GENERATED by supabase/scripts/generate-seed.mjs from web/lib/diseases.ts — do not edit by hand.

-- Models the ML service can report (set MODEL_VERSION in ml-service/.env to one of these).
insert into model_versions (version, architecture, accuracy, source_url, is_active) values
  ('dinov2-small-plantvillage-int8', 'DINOv2-small + linear head, int8 ONNX (38 PlantVillage classes)', 98.70,
   'https://huggingface.co/rodynaemad/plant-disease-dinov2-small', true),
  ('mobilenet-v2-plantvillage', 'MobileNetV2 1.0 224, ONNX (38 PlantVillage classes)', 95.41,
   'https://huggingface.co/linkanjarad/mobilenet_v2_1.0_224-plant-disease-identification', false),
  ('demo-heuristic', 'Colour heuristic used by the frontend demo mode (not a model)', null, null, false)
on conflict (version) do update set architecture = excluded.architecture, accuracy = excluded.accuracy,
  source_url = excluded.source_url, is_active = excluded.is_active;

insert into diseases (slug, label, name, pathogen, pathogen_type, severity, deck, summary, short_symptom, symptoms,
  conditions, favourable_conditions, spread_mode, treatment_organic, treatment_chemical, prevention, related) values
${rows.join(",\n")}
on conflict (slug) do update set
  label = excluded.label, name = excluded.name, pathogen = excluded.pathogen, pathogen_type = excluded.pathogen_type,
  severity = excluded.severity, deck = excluded.deck, summary = excluded.summary, short_symptom = excluded.short_symptom,
  symptoms = excluded.symptoms, conditions = excluded.conditions, favourable_conditions = excluded.favourable_conditions,
  spread_mode = excluded.spread_mode, treatment_organic = excluded.treatment_organic,
  treatment_chemical = excluded.treatment_chemical, prevention = excluded.prevention, related = excluded.related;
`;

const out = path.join(here, "../migrations/0004_seed.sql");
writeFileSync(out, sql);
console.log(`Wrote ${out} (${diseases.length} diseases)`);
